export type I18nKey = keyof typeof zh;

export function resolveLocale(value?: string | null): Locale {
  return value?.toLowerCase().startsWith("en") ? "en" : "zh-CN";
}

export function currentLocale(): Locale {
  return resolveLocale(document.documentElement.lang || (typeof navigator !== "undefined" ? navigator.language : "zh-CN"));
}

export function interpolate(template: string, values: Values = {}) {
  return template.replace(/\{(\w+)\}/g, (_match, key) => String(values[key] ?? ""));
}

export function translate(locale: Locale, key: string, values?: Values): string {
  const dict = locale === "en" ? en : zh;
  const fallback = locale === "en" ? zh : en;
  const template = (dict as Record<string, string>)[key] ?? (fallback as Record<string, string>)[key] ?? key;
  return interpolate(template, values);
}

const I18nContext = createContext<{
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: I18nKey | string, values?: Values) => string;
} | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() =>
    resolveLocale(localStorage.getItem("semaloom.locale") || navigator.language),
  );

  const value = useMemo(() => ({
    locale,
    setLocale(next: Locale) {
      localStorage.setItem("semaloom.locale", next);
      document.documentElement.lang = next;
      setLocaleState(next);
    },
    t(key: I18nKey | string, values?: Values) {
      return translate(locale, key, values);
    },
  }), [locale]);

  document.documentElement.lang = locale;
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error("I18nProvider is required");
  return value;
}
